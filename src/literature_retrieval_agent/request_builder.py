from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping

from literature_retrieval_agent.config import (
    DEFAULT_CONFIG,
    LiteratureRetrievalConfig,
)
from literature_retrieval_agent.schemas import (
    CandidateAnnotation,
    LiteratureRequest,
    MarkerGene,
    ReviewFlag,
)


def load_agent2_handoff(
    path: str | Path,
) -> tuple[dict[str, Any], Path]:
    """
    Load the complete Agent 2 cluster evidence JSON.

    Agent 3 consumes the complete MarkerEvidence JSON,
    not only the follow-up gene queue.
    """

    source = Path(path).expanduser().resolve()

    if not source.exists():
        raise FileNotFoundError(
            f"Agent 2 JSON does not exist: {source}"
        )

    if not source.is_file():
        raise ValueError(
            f"Agent 2 path is not a file: {source}"
        )

    with source.open(
        "r",
        encoding="utf-8",
    ) as handle:
        payload = json.load(handle)

    if not isinstance(payload, dict):
        raise ValueError(
            "Agent 2 JSON root must be an object."
        )

    return payload, source


def _required_text(
    payload: Mapping[str, Any],
    key: str,
) -> str:
    """Read and validate a required Agent 2 field."""

    value = " ".join(
        str(payload.get(key, "")).split()
    )

    if not value:
        raise ValueError(
            "Agent 2 JSON is missing required "
            f"field {key!r}."
        )

    return value


def _build_markers(
    payload: Mapping[str, Any],
    marker_count: int | None,
) -> list[MarkerGene]:
    """Preserve marker genes and statistics from Agent 2."""

    records = payload.get("input_genes")

    if not isinstance(records, list) or not records:
        raise ValueError(
            "Agent 2 JSON contains no input_genes."
        )

    markers = [
        MarkerGene.model_validate(record)
        for record in records
    ]

    markers.sort(
        key=lambda item: item.rank_within_cluster
    )

    if marker_count is None:
        return markers

    if marker_count <= 0:
        raise ValueError(
            "marker_count must be greater than zero."
        )

    return markers[:marker_count]


def _build_candidates(
    payload: Mapping[str, Any],
    candidate_count: int,
) -> list[CandidateAnnotation]:
    """Read the highest-ranked Agent 2 candidates."""

    if candidate_count <= 0:
        raise ValueError(
            "candidate_count must be greater than zero."
        )

    records = payload.get(
        "ranked_candidate_cell_types"
    )

    if not isinstance(records, list) or not records:
        raise ValueError(
            "Agent 2 JSON contains no "
            "ranked_candidate_cell_types."
        )

    ordered_records = sorted(
        records,
        key=lambda item: int(
            item.get(
                "candidate_rank",
                10**9,
            )
        ),
    )

    candidates: list[CandidateAnnotation] = []

    for record in ordered_records[:candidate_count]:
        candidates.append(
            CandidateAnnotation(
                name=str(
                    record.get("cell_type", "")
                ),
                upstream_rank=record.get(
                    "candidate_rank"
                ),
                supporting_genes=(
                    record.get("supporting_genes")
                    or []
                ),
                evidence_sources=(
                    record.get("evidence_sources")
                    or []
                ),
            )
        )

    return candidates


def _build_review_flags(
    payload: Mapping[str, Any],
) -> list[ReviewFlag]:
    """Preserve review flags generated by Agent 2."""

    records = payload.get("review_flags") or []

    if not isinstance(records, list):
        raise ValueError(
            "Agent 2 review_flags must be a list."
        )

    return [
        ReviewFlag.model_validate(record)
        for record in records
    ]


def build_literature_request(
    payload: Mapping[str, Any],
    *,
    source_file: str | Path,
    disease_context: str,
    candidate_count: int,
    marker_count: int | None = None,
    question: str | None = None,
    spatial_context: str | None = None,
    config: LiteratureRetrievalConfig = DEFAULT_CONFIG,
) -> LiteratureRequest:
    """
    Transform the complete Agent 2 output into an
    Agent 3 literature request.
    """

    cluster_id = _required_text(
        payload,
        "cluster_id",
    )

    candidates = _build_candidates(
        payload,
        candidate_count,
    )

    request_question = " ".join(
        str(question or "").split()
    )

    if not request_question:
        request_question = (
            "What published evidence supports or "
            "contradicts the proposed candidate "
            "annotations for this cluster, and which "
            "marker combinations distinguish them?"
        )

    cleaned_spatial_context = None

    if spatial_context:
        cleaned_spatial_context = " ".join(
            str(spatial_context).split()
        )

    return LiteratureRequest(
        schema_name=config.request_schema_name,
        schema_version=config.request_schema_version,
        cluster_id=cluster_id,
        species=_required_text(
            payload,
            "species",
        ),
        tissue=_required_text(
            payload,
            "tissue",
        ),
        disease_context=" ".join(
            str(disease_context).split()
        ),
        platform=_required_text(
            payload,
            "platform",
        ),
        marker_genes=_build_markers(
            payload,
            marker_count,
        ),
        candidate_annotations=candidates,
        review_flags=_build_review_flags(
            payload
        ),
        spatial_context=cleaned_spatial_context,
        question=request_question,
        upstream_schema_name=_required_text(
            payload,
            "schema_name",
        ),
        upstream_schema_version=_required_text(
            payload,
            "schema_version",
        ),
        source_agent2_file=str(
            Path(source_file).expanduser().resolve()
        ),
    )